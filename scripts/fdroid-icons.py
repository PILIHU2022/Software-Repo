#!/usr/bin/env python3
"""Keep the F-Droid index icons in sync with fdroid/icons-src/.

`fdroid update` extracts icons from APKs, but the apps here use adaptive
(XML) launcher icons, which fdroidserver cannot rasterize.  As a result it
leaves the icons of these apps empty in all three index generations:

  * index-v2.json  content-addressed ``repo/<pkg>/<locale>/icon_<hash>.png``
                   (and the ``metadata.icon`` that points at it);
  * index-v1.json  the legacy ``apps[].icon`` filename under ``icons/``;
  * index.xml      the legacy v0 ``<application><icon>`` element, with per
                   density copies in ``icons-<density>/`` and the whole file
                   packed into ``index.jar``.

It can also prune content-addressed index-v2 icons when a new package is
added.  This script restores every one of those forms from the per-app icon
sources in ``fdroid/icons-src/``:

  * puts the 512x512 source back at the content-addressed v2 name that
    index-v2.json already expects (only when the file is missing/stale, and
    only if the source hash matches the index, so a real mismatch is still an
    error instead of being papered over);
  * patches ``apps[].icon`` in index-v1.json;
  * writes ``<icon>`` into every legacy ``<application>`` of index.xml and
    down-scales the source into ``icons-<density>/`` for the 120..640 dpi
    buckets (matching fdroidserver's ``dpi_to_px`` sizing);
  * rebuilds ``index_unsigned.jar`` from the patched index.xml and, when a
    ``fdroid`` executable can be found, runs ``fdroid signindex`` so that
    ``index.jar`` (and ``index-v1.jar`` / ``entry.jar``) match the files on
    disk.

Usage:
  scripts/fdroid-icons.py --repo fdroid/repo
  scripts/fdroid-icons.py --repo fdroid/repo --check

``--check`` verifies all three index generations (v0, v1, v2) and that the
``index.xml`` packed inside ``index.jar`` matches the file on disk.
"""

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

try:
    from PIL import Image
except ImportError:  # pragma: no cover - Pillow is a hard runtime need here
    Image = None


# fdroidserver's screen densities (anydpi '65534'/'0' are skipped: they cannot
# be generated by down-scaling a raster source).
SCREEN_DENSITIES = ["640", "480", "320", "240", "160", "120"]

APP_RE = re.compile(r'(<application id="([^"]+)">)(.*?)(</application>)', re.S)
ICON_RE = re.compile(r'<icon>.*?</icon>', re.S)


def load(path):
    with path.open(encoding="utf-8") as fp:
        return json.load(fp)


def sha256(path):
    digest = hashlib.sha256()
    with path.open("rb") as fp:
        for chunk in iter(lambda: fp.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def dpi_to_px(density):
    """Match fdroidserver.update.dpi_to_px so density buckets stay identical."""
    return (int(density) * 48) // 160


def choose_icon(icons, package, preferred):
    """Return the filename of the best icons/<package>.<versionCode>.png."""
    preferred = str(preferred or "")
    if preferred:
        name = f"{package}.{preferred}.png"
        if (icons / name).is_file():
            return name

    candidates = []
    pattern = re.compile(r"^" + re.escape(package) + r"\.(\d+)\.png$")
    for path in icons.glob(f"{package}.*.png"):
        match = pattern.match(path.name)
        if match:
            candidates.append((int(match.group(1)), path.name))
    if not candidates:
        return None
    return max(candidates)[1]


def icon_source(repo, package, locale):
    """Return the best source icon for a package and locale."""
    for path in (
        repo.parent / "icons-src" / f"{package}.png",
        repo / package / locale / "icon.png",
    ):
        if path.is_file():
            return path
    return None


def restore_index_v2_icons(repo):
    """Restore content-addressed icons that fdroid update may have pruned.

    When a new package is added, fdroidserver can drop the existing
    repo/<package>/<locale>/icon_<hash>.png files while keeping the old
    references in index-v2.json.  The index is then inconsistent until the
    files are put back, so copy the source icon to the name and hash the index
    already expects.

    index-v2.json must not be rewritten here: entry.json records its sha256 and
    `fdroid signindex` refuses a hash mismatch, so only a repository-wide
    `fdroid update` may change the index.  A source icon that no longer matches
    its index entry is therefore an error, not something to paper over.
    """
    index = repo / "index-v2.json"
    if not index.is_file():
        return 0

    data = load(index)
    changed = 0
    for package, entry in data.get("packages", {}).items():
        icon = entry.get("metadata", {}).get("icon")
        if not isinstance(icon, dict):
            continue
        for locale, meta in icon.items():
            if not isinstance(meta, dict):
                continue
            name = meta.get("name")
            expected = meta.get("sha256")
            target = repo / name.lstrip("/") if isinstance(name, str) else None
            if target is not None and target.is_file():
                if not expected or sha256(target) == expected:
                    continue

            source = icon_source(repo, package, locale)
            if source is None:
                print(f"    no icon source for {package} ({locale})")
                continue

            content = source.read_bytes()
            digest = hashlib.sha256(content).hexdigest()
            if not isinstance(name, str) or not expected or digest != expected:
                raise SystemExit(
                    f"icon source for {package} ({locale}) does not match the "
                    f"index (expected {expected}, got {digest}); regenerate "
                    "fdroid/icons-src and the repository index"
                )

            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content)
            print(f"    restored {package} ({locale}): {target.relative_to(repo)}")
            changed += 1

    if changed:
        print(f"    restored {changed} index-v2 icon(s)")
    else:
        print("    index-v2 icons already current")
    return changed


def patch_index_v1(repo):
    """Patch apps[].icon in index-v1.json; return {package: icon filename}."""
    index = repo / "index-v1.json"
    if not index.is_file():
        raise SystemExit(f"missing {index}")
    data = load(index)
    icons = repo / "icons"
    changed = 0
    icon_map = {}
    for app in data.get("apps", []):
        package = app.get("packageName")
        if not package:
            continue
        name = choose_icon(icons, package, app.get("suggestedVersionCode"))
        if name is None:
            source = icon_source(repo, package, "en-US")
            code = app.get("suggestedVersionCode")
            if source is not None and code:
                name = f"{package}.{code}.png"
                target = icons / name
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(source.read_bytes())
                print(f"    restored legacy icon {package} ({code})")
                changed += 1
                app["icon"] = name
            else:
                print(f"    no icon for {package} (add fdroid/icons-src/{package}.png)")
                continue
        else:
            if app.get("icon") != name:
                app["icon"] = name
                changed += 1
        icon_map[package] = name
    if changed:
        with index.open("w", encoding="utf-8") as fp:
            json.dump(data, fp, separators=(",", ":"))
        print(f"    patched {changed} index-v1 icon(s)")
    else:
        print("    index-v1 icons already current")
    return icon_map


def _set_icon_in_body(body, name):
    """Insert/replace <icon> in an <application> body, matching v0 order.

    fdroidserver emits <icon> right after <summary> and before <desc>, so we
    insert it at the same spot to keep the document layout stable.
    """
    element = f"<icon>{name}</icon>"
    if ICON_RE.search(body):
        return ICON_RE.sub(element, body, count=1)
    for anchor in ("</summary>", "</name>", "</lastupdated>"):
        idx = body.find(anchor)
        if idx != -1:
            end = idx + len(anchor)
            return body[:end] + element + body[end:]
    return element + body


def patch_index_xml(repo, icon_map):
    """Write legacy <icon> elements into index.xml; return whether it changed."""
    path = repo / "index.xml"
    if not path.is_file():
        print("    no index.xml (legacy v0 index) to patch")
        return False

    text = path.read_text(encoding="utf-8")
    changed = [False]

    def repl(match):
        open_tag, package, body, close = (
            match.group(1),
            match.group(2),
            match.group(3),
            match.group(4),
        )
        name = icon_map.get(package)
        if not name:
            return match.group(0)
        new_body = _set_icon_in_body(body, name)
        if new_body != body:
            changed[0] = True
        return open_tag + new_body + close

    new_text = APP_RE.sub(repl, text)
    if changed[0]:
        path.write_text(new_text, encoding="utf-8")
        count = len(APP_RE.findall(new_text))
        print(f"    patched legacy index.xml icon(s) for {count} application(s)")
    else:
        print("    index.xml icons already current")
    return changed[0]


def generate_density_icons(repo, icon_map):
    """Down-scale each icon into icons-<density>/ for every screen density."""
    if Image is None:
        raise SystemExit(
            "Pillow is required to generate per-density icons "
            "(install python3-pil or use .toolchain/fdroid-venv)"
        )

    written = 0
    for package, name in sorted(icon_map.items()):
        source = repo / "icons" / name
        if not source.is_file():
            source = icon_source(repo, package, "en-US")
        if source is None or not source.is_file():
            print(f"    no icon source for {package}; skipping density icons")
            continue
        with Image.open(source) as original:
            original.load()
            for density in SCREEN_DENSITIES:
                size = dpi_to_px(density)
                icon = original.copy()
                # fdroidserver only ever shrinks; thumbnail keeps that contract
                # and preserves aspect ratio for non-square sources.
                icon.thumbnail((size, size), Image.LANCZOS)
                dest_dir = repo / f"icons-{density}"
                dest_dir.mkdir(parents=True, exist_ok=True)
                dest = dest_dir / name
                icon.save(dest, "PNG", optimize=True)
                written += 1
    print(f"    wrote {written} per-density icon(s) across "
          f"{len(SCREEN_DENSITIES)} densit(ies)")
    return written


def _find_fdroid_bin(repo, explicit):
    """Locate a `fdroid` executable to run `fdroid signindex`."""
    if explicit:
        return explicit if os.access(explicit, os.X_OK) else None
    env = os.environ.get("FDROID_BIN")
    if env and os.access(env, os.X_OK):
        return env
    root = repo.parent.parent  # <root>/fdroid/repo -> <root>
    candidate = root / ".toolchain" / "fdroid-venv" / "bin" / "fdroid"
    if candidate.is_file() and os.access(candidate, os.X_OK):
        return str(candidate)
    found = shutil.which("fdroid")
    return found


def rebuild_and_sign_index(repo, fdroid_bin, sign):
    """Rebuild index_unsigned.jar from index.xml and (optionally) sign index.jar.

    `fdroid signindex` does not regenerate index.jar from index.xml: it only
    signs an existing ``index_unsigned.jar`` and renames it.  So we always build
    the unsigned jar from the patched index.xml here; if a fdroid executable is
    available (or asked for), signindex then produces index.jar plus refreshed
    index-v1.jar / entry.jar.
    """
    jar = shutil.which("jar")
    if not jar:
        raise SystemExit("the `jar` tool is required to rebuild index_unsigned.jar")

    unsigned = repo / "index_unsigned.jar"
    if unsigned.exists():
        unsigned.unlink()
    result = subprocess.run(
        [jar, "cf", unsigned.name, "index.xml"],
        cwd=str(repo),
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
    )
    if result.returncode != 0:
        raise SystemExit(f"failed to build index_unsigned.jar:\n{result.stdout}")
    print("    rebuilt index_unsigned.jar from index.xml")

    if not sign:
        print("    --no-sign: leaving index_unsigned.jar for a later "
              "`fdroid signindex` (publish-fdroid.sh runs it next)")
        return

    if fdroid_bin is None:
        print("    no fdroid executable found; leaving index_unsigned.jar for "
              "`fdroid signindex` (run it before --check)")
        return

    env = dict(os.environ)
    if not env.get("ANDROID_HOME"):
        sdk = repo.parent.parent / ".toolchain" / "android-sdk"
        if sdk.is_dir():
            env["ANDROID_HOME"] = str(sdk)
    proc = subprocess.run(
        [fdroid_bin, "signindex"],
        cwd=str(repo.parent),
        env=env,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
    )
    if proc.returncode != 0:
        raise SystemExit(f"`fdroid signindex` failed:\n{proc.stdout}")
    tail = [line for line in proc.stdout.splitlines() if line.strip()]
    print("    fdroid signindex: ok")
    for line in tail[-6:]:
        print(f"      {line}")


def patch(repo, sign=True, fdroid_bin=None):
    restore_index_v2_icons(repo)
    icon_map = patch_index_v1(repo)
    patch_index_xml(repo, icon_map)
    generate_density_icons(repo, icon_map)
    rebuild_and_sign_index(repo, fdroid_bin, sign)
    return 0


def check(repo):
    errors = []
    v2_path = repo / "index-v2.json"
    v1_path = repo / "index-v1.json"
    xml_path = repo / "index.xml"
    if not v2_path.is_file() or not v1_path.is_file():
        print("missing index-v1.json or index-v2.json", file=sys.stderr)
        return 1

    # --- v2: content-addressed icons ---
    v2 = load(v2_path)
    for package, entry in v2.get("packages", {}).items():
        icon = entry.get("metadata", {}).get("icon")
        if not icon:
            errors.append(f"{package}: index-v2 has no icon")
            continue
        for locale, meta in icon.items():
            name = meta.get("name", "")
            path = repo / name.lstrip("/")
            if not path.is_file():
                errors.append(f"{package} ({locale}): missing {path}")
            elif sha256(path) != meta.get("sha256"):
                errors.append(f"{package} ({locale}): sha256 mismatch for {path}")

    # --- v1: legacy apps[].icon + icons/<name> ---
    v1 = load(v1_path)
    for app in v1.get("apps", []):
        package = app.get("packageName")
        name = app.get("icon")
        if not package:
            continue
        if not name:
            errors.append(f"{package}: index-v1 has no icon")
        elif not (repo / "icons" / name).is_file():
            errors.append(f"{package}: missing icons/{name}")

    # --- v0: legacy index.xml <icon> + icons/<name> + icons-<density>/<name> ---
    if not xml_path.is_file():
        errors.append("missing index.xml")
    else:
        text = xml_path.read_text(encoding="utf-8")
        apps = APP_RE.findall(text)
        if not apps:
            errors.append("index.xml has no <application> elements")
        for _open, package, body, _close in apps:
            match = re.search(r"<icon>([^<]*)</icon>", body)
            if not match or not match.group(1).strip():
                errors.append(f"{package}: index-v0 (index.xml) has no <icon>")
                continue
            name = match.group(1).strip()
            if not (repo / "icons" / name).is_file():
                errors.append(f"{package}: index-v0 missing icons/{name}")
            for density in SCREEN_DENSITIES:
                if not (repo / f"icons-{density}" / name).is_file():
                    errors.append(
                        f"{package}: index-v0 missing icons-{density}/{name}"
                    )

        # index.jar must carry the same index.xml that is on disk
        index_jar = repo / "index.jar"
        if index_jar.is_file():
            try:
                with zipfile.ZipFile(index_jar) as jar:
                    jar_xml = jar.read("index.xml")
            except (KeyError, zipfile.BadZipFile) as exc:
                errors.append(f"index.jar is unreadable: {exc}")
                jar_xml = None
            if jar_xml is not None and jar_xml != xml_path.read_bytes():
                errors.append(
                    "index.jar's index.xml does not match index.xml on disk "
                    "(run `fdroid signindex`)"
                )

    if errors:
        for error in errors:
            print(f"ERROR: {error}", file=sys.stderr)
        return 1
    print(f"    icons OK (v0/v1/v2): {len(v1.get('apps', []))} app(s)")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", required=True, type=Path)
    parser.add_argument("--check", action="store_true")
    parser.add_argument(
        "--no-sign",
        action="store_true",
        help="build index_unsigned.jar but do not run `fdroid signindex`",
    )
    parser.add_argument(
        "--fdroid-bin",
        default=None,
        help="path to the fdroid executable used for `fdroid signindex`",
    )
    args = parser.parse_args()
    repo = args.repo.resolve()
    if args.check:
        return check(repo)
    return patch(repo, sign=not args.no_sign, fdroid_bin=args.fdroid_bin)


if __name__ == "__main__":
    sys.exit(main())
